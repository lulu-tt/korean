# 같은 항목을 두 번 적는 실수를 막기 위한 병합 (코드 뒤 b 접미사 허용)
_merged = {}
for _k, _v in DRAFT.items():
    _code = _k.rstrip('b')
    if _code in _merged:
        _merged[_code] = (_merged[_code][0], _merged[_code][1] + _v[1])
    else:
        _merged[_code] = _v
DRAFT = _merged

def main():
    items, n, nrev = {}, 0, 0
    for code, (word, forms) in sorted(DRAFT.items()):
        allow = []
        for f, why, rev in forms:
            allow.append({'form': f, 'why': why, **({'review': True} if rev else {})})
            n += 1
            nrev += bool(rev)
        items[code] = {'word': word, 'allow': allow}
    out = {
        'meta': {
            'title': '표준어 허용형 목록 (초안 · 검토 필요)',
            'policy': ['① 복수표준어·표준어 대체어', '② 표기 이형(사이시옷·된소리·받침)',
                       '③ 표제어 괄호 병기형·활용형·부분 발화'],
            'keep': '모음·자음 교체형, 접미사 차이형, 어휘가 다른 형태는 지역어형으로 유지',
            'basis': '보고서 4.2 코딩 기준 — 표준어형(복수 표준어 포함)을 표준어 사용(1)로 봄',
            'items': len(items), 'forms': n, 'needReview': nrev,
        },
        'items': items,
    }
    with io.open(OUT, 'w', encoding='utf-8') as fp:
        json.dump(out, fp, ensure_ascii=False, indent=1)
    print('허용형 %d건 (검토 필요 %d건) / %d개 항목 → %s' % (n, nrev, len(items), OUT))

if __name__ == '__main__':
    main()
